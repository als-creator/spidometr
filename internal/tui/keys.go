package tui

import "github.com/gdamore/tcell/v2"

// cyrillicHotkeys сопоставляет буквы, которые получаются при нажатии тех же
// физических клавиш в русской/украинской раскладке, латинским горячим клавишам.
// Так s/p/t/d/u/r/l/h/q работают независимо от активной раскладки.
var cyrillicHotkeys = map[rune]rune{
	// ЙЦУКЕН, нижний регистр.
	'й': 'q', 'ц': 'w', 'у': 'e', 'к': 'r', 'е': 't', 'н': 'y', 'г': 'u',
	'ш': 'i', 'щ': 'o', 'з': 'p', 'ф': 'a', 'ы': 's', 'в': 'd', 'а': 'f',
	'п': 'g', 'р': 'h', 'о': 'j', 'л': 'k', 'д': 'l', 'я': 'z', 'ч': 'x',
	'с': 'c', 'м': 'v', 'и': 'b', 'т': 'n', 'ь': 'm',
	// ЙЦУКЕН, верхний регистр.
	'Й': 'q', 'Ц': 'w', 'У': 'e', 'К': 'r', 'Е': 't', 'Н': 'y', 'Г': 'u',
	'Ш': 'i', 'Щ': 'o', 'З': 'p', 'Ф': 'a', 'Ы': 's', 'В': 'd', 'А': 'f',
	'П': 'g', 'Р': 'h', 'О': 'j', 'Л': 'k', 'Д': 'l', 'Я': 'z', 'Ч': 'x',
	'С': 'c', 'М': 'v', 'И': 'b', 'Т': 'n', 'Ь': 'm',
	// Украинская раскладка: те же физические клавиши для нужных hotkey.
	'і': 's', 'І': 's',
}

// hotkey возвращает латинскую клавишу для события, если оно было буквой.
func hotkey(event *tcell.EventKey) rune {
	if event.Key() != tcell.KeyRune {
		return 0
	}
	r := event.Rune()
	if mapped, ok := cyrillicHotkeys[r]; ok {
		return mapped
	}
	if r >= 'A' && r <= 'Z' {
		return r + ('a' - 'A')
	}
	return r
}
